// Пот-оддсы: формулы, которые покерист проверяет в уме, — значит и тест должен
// читаться так же. Числа взяты из классических примеров.
import { test } from "node:test";
import assert from "node:assert/strict";
import { computePotOdds } from "../../src/engine/potodds.ts";

const близко = (было: number, ждём: number, допуск: number, что: string) =>
  assert.ok(Math.abs(было - ждём) <= допуск, `${что}: получили ${было.toFixed(2)}, ждали ${ждём} ±${допуск}`);

test("ставка в половину банка", () => {
  // Банк 100, соперник ставит 50. Коллируем 50 в банк 200 → нужно 25% эквити.
  const r = computePotOdds(100, 50)!;
  близко(r.reqEquity, 25, 0.01, "нужная эквити");
  близко(r.mdf, 66.67, 0.01, "минимальная частота защиты");
  близко(r.alpha, 33.33, 0.01, "блеф-частота соперника");
  близко(r.betToPot, 0.5, 1e-9, "отношение ставки к банку");
});

test("ставка в размер банка", () => {
  // Классика: пот-бет требует 33% эквити, защищать надо половину диапазона.
  const r = computePotOdds(100, 100)!;
  близко(r.reqEquity, 33.33, 0.01, "нужная эквити");
  близко(r.mdf, 50, 0.01, "минимальная частота защиты");
  близко(r.alpha, 50, 0.01, "блеф-частота");
});

test("маленькая ставка требует мало эквити, большая — много", () => {
  const четверть = computePotOdds(100, 25)!;
  const банк = computePotOdds(100, 100)!;
  const овербет = computePotOdds(100, 200)!;
  assert.ok(
    четверть.reqEquity < банк.reqEquity && банк.reqEquity < овербет.reqEquity,
    `порядок нарушен: ${четверть.reqEquity} / ${банк.reqEquity} / ${овербет.reqEquity}`,
  );
  // И защищаться против крупной ставки надо реже — это то же правило с другой стороны.
  assert.ok(четверть.mdf > банк.mdf && банк.mdf > овербет.mdf, "MDF обязан падать с ростом ставки");
});

test("MDF и блеф-частота всегда дают в сумме сто процентов", () => {
  for (const [банк, ставка] of [[100, 50], [30, 10], [7, 13], [1000, 1]]) {
    const r = computePotOdds(банк, ставка)!;
    близко(r.mdf + r.alpha, 100, 1e-9, `банк ${банк}, ставка ${ставка}`);
  }
});

test("бессмысленный ввод — не ноль и не падение, а «считать нечего»", () => {
  assert.equal(computePotOdds(100, 0), null, "нулевая ставка");
  assert.equal(computePotOdds(100, -5), null, "отрицательная ставка");
  assert.equal(computePotOdds("абв", 50), null, "мусор в поле банка");
  assert.equal(computePotOdds(100, ""), null, "пустая ставка");
});

test("банк пустой: ставка в сухой банк", () => {
  const r = computePotOdds(0, 50)!;
  близко(r.reqEquity, 50, 0.01, "в пустой банк нужно 50%");
  assert.equal(r.betToPot, Infinity, "отношение к нулевому банку — бесконечность, а не деление на ноль");
});
