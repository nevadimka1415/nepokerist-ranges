// Проверки турнирной математики. Здесь особенно важно проверять не «работает ли»,
// а «правильно ли»: чарт пуш/фолда нарисуется одинаково красиво при любой арифметике.
//
// Запуск: npm run test:unit
import { test } from "node:test";
import assert from "node:assert/strict";
import { icmEquities, solveIcmPushFold } from "../../src/engine/icm.ts";

const близко = (было: number, ждём: number, допуск: number, что: string) =>
  assert.ok(Math.abs(было - ждём) <= допуск, `${что}: получили ${было.toFixed(4)}, ждали ${ждём.toFixed(4)} ±${допуск}`);

test("весь призовой фонд распределяется без остатка", () => {
  const доли = icmEquities([5000, 3000, 2000], [50, 30, 20]);
  близко(доли.reduce((a, b) => a + b, 0), 100, 0.001, "сумма долей");
});

test("больше фишек — больше денег, и это строго", () => {
  const [большой, средний, малый] = icmEquities([5000, 3000, 2000], [50, 30, 20]);
  assert.ok(большой > средний && средний > малый, `порядок нарушен: ${большой} / ${средний} / ${малый}`);
});

test("равные стеки — равные доли", () => {
  const доли = icmEquities([1000, 1000, 1000], [50, 30, 20]);
  близко(доли[0], доли[1], 1e-9, "первый и второй");
  близко(доли[1], доли[2], 1e-9, "второй и третий");
});

test("один на один: доля пропорциональна стеку, но не линейно по деньгам", () => {
  // 80/20 по фишкам при выплатах 65/35 даёт примерно 59/41 — вот она, суть ICM:
  // фишки лидера стоят дешевле, фишки шорта дороже.
  const [лидер, шорт] = icmEquities([8000, 2000], [65, 35]);
  близко(лидер, 59, 0.5, "лидер");
  близко(шорт, 41, 0.5, "шорт");
  близко(лидер + шорт, 100, 1e-9, "сумма");
});

test("вылетевший игрок получает нижнее место, а не ноль и не NaN", () => {
  const доли = icmEquities([9000, 1000, 0], [50, 30, 20]);
  assert.ok(Number.isFinite(доли[2]), "доля вылетевшего должна быть числом");
  близко(доли[2], 20, 1e-9, "вылетевший забирает третье место");
  близко(доли.reduce((a, b) => a + b, 0), 100, 1e-9, "сумма всё равно сходится");
});

test("пуш на 10 больших блайндов сходится с известными таблицами", () => {
  // Один на один, равные стеки по 10ББ. Классический ориентир: кнопка пушит
  // около 58% рук. Проверяли против HoldemResources — расхождение было 0.1%.
  const r = solveIcmPushFold([10, 10], 0, 1, [65, 35], 300);
  близко(r.pushPct, 58.5, 3, "доля рук в пуше на 10ББ");
  assert.ok(r.pushLabels.size > 90, `рук в пуше должно быть под сотню, а вышло ${r.pushLabels.size}`);
  assert.ok(r.pushLabels.has("AA") && r.pushLabels.has("A2s"), "тузы и одномастные с тузом обязаны пушиться");
});

test("колл всегда у́же пуша — иначе это не равновесие", () => {
  const r = solveIcmPushFold([10, 10], 0, 1, [65, 35], 300);
  assert.ok(
    r.callPct < r.pushPct,
    `коллировать надо у́же, чем пушить: колл ${r.callPct.toFixed(1)}% против пуша ${r.pushPct.toFixed(1)}%`,
  );
});

test("чем короче стек, тем шире пуш", () => {
  const пуш = (стек: number) => solveIcmPushFold([стек, стек], 0, 1, [65, 35], 300).pushPct;
  const на5 = пуш(5);
  const на10 = пуш(10);
  const на20 = пуш(20);
  assert.ok(
    на5 > на10 && на10 > на20,
    `порядок нарушен: 5ББ ${на5.toFixed(1)}%, 10ББ ${на10.toFixed(1)}%, 20ББ ${на20.toFixed(1)}%`,
  );
});
